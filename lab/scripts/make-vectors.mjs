// Regenerates src/shared/labMonth.vectors.json from the live GET /api/sample templates.
// Run: node scripts/make-vectors.mjs
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const out = path.resolve("node_modules/.cache/labMonth.mjs");
await build({ entryPoints: ["src/shared/labMonth.ts"], outfile: out, format: "esm", bundle: true, logLevel: "error" });
const { buildLabMonth, encodeLabLink, parseLabLink } = await import(pathToFileURL(out).href);
const api = "https://kahati.vercel.app";
const [compound, bau] = await Promise.all(["compound", "bautista"].map((w) => fetch(`${api}/api/sample?which=${w}`).then((r) => r.json())));
const templates = { compound, bau };

const cases = [
  { seed: 7802, minKwh: 20, maxKwh: 80, gap: false, newSerials: false, fourPs: [false, true, true, true, true] },
  { seed: 4605, minKwh: 20, maxKwh: 80, gap: true, newSerials: false, fourPs: [false, true, true, true, true] },
  { seed: 1234, minKwh: 20, maxKwh: 80, gap: false, newSerials: true, fourPs: [true, false, true, false, true] },
  { seed: 8591, minKwh: 30, maxKwh: 120, gap: true, newSerials: true, fourPs: [false, false, false, false, false] },
  { seed: 1, minKwh: 5, maxKwh: 15, gap: true, newSerials: false, fourPs: [true, true, true, true, true] },
  { seed: 999999, minKwh: 80, maxKwh: 20, gap: false, newSerials: true, fourPs: [false, true, false, true, false] },
];
const vectors = cases.map((opts) => {
  const link = encodeLabLink(opts);
  const back = parseLabLink(link);
  if (JSON.stringify(back) !== JSON.stringify(opts)) throw new Error("link round trip failed for " + link);
  const s = buildLabMonth(templates, opts);
  const c = s.compound;
  const val = (list, m) => list.find((r) => r.meterId === m).value;
  return {
    link,
    opts,
    expect: {
      name: c.compound.displayName,
      billKwh: c.bill.kwh,
      amount: c.bill.amount,
      lines: c.bill.lines,
      billPrevious: c.bill.previousReading,
      billPresent: c.bill.presentReading,
      households: ["A", "B", "C", "D"].map((L) => ({
        id: "h" + L,
        previous: val(c.previousReadings, "m" + L), // includes +18 for the gap household
        current: val(c.currentReadings, "m" + L),
        serial: c.meters.find((m) => m.id === "m" + L).serial,
        fourPs: c.households.find((h) => h.id === "h" + L).fourPs,
      })),
      bau: {
        name: s.bau.households[0].displayName,
        readDay: s.bau.previousReadings[0].value,
        day18: s.bau.currentReadings[0].value,
        serial: s.bau.meters[0].serial,
        fourPs: s.bau.households[0].fourPs,
      },
    },
  };
});
fs.writeFileSync("src/shared/labMonth.vectors.json", JSON.stringify({ note: "Generated by stress-lab/scripts/make-vectors.mjs from the live /api/sample templates.", vectors }, null, 2) + "\n");
for (const v of vectors) console.log(v.link, "->", v.expect.billKwh, "kWh", v.expect.amount, v.expect.households.map((h) => `${h.previous}/${h.current}/${h.serial}`).join(" "), "| bau", v.expect.bau.readDay, v.expect.bau.day18, v.expect.bau.serial);
